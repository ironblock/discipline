/// Without this, emptying `FORMATS` would make every sweep iterate nothing
/// and pass. A harness that covers no formats must be red, not quiet.
#[test]
fn the_harness_covers_at_least_one_format() {
    assert!(
        !FORMATS.is_empty(),
        "FORMATS is empty, so this harness covers nothing"
    );
}

/// A format directory on disk that `FORMATS` does not name is a format with
/// no grammar requirement and no fixture requirement at all. Coverage must
/// not be a hand-maintained opinion about what exists.
#[test]
fn no_format_directory_is_undeclared() {
    let root = formats_dir();
    let declared: BTreeSet<&str> = FORMATS.iter().map(|format| format.name).collect();
    let mut failures = Vec::new();

    for entry in files_in_or_empty(&root) {
        if !entry.is_dir() {
            continue;
        }
        let Some(name) = entry.file_name().and_then(std::ffi::OsStr::to_str) else {
            failures.push(format!("{}: unreadable directory name", entry.display()));
            continue;
        };
        if !declared.contains(name) {
            failures.push(format!(
                "{name}: has a directory under formats/ but is absent from FORMATS, \
                 so nothing requires it to have a grammar or fixtures"
            ));
        }
    }

    report(&failures);
}
