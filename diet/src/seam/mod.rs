vocabulary! {
    /// Why a seam fired.
    ///
    /// **Declaration order is precedence.** Where two triggers are true at
    /// once, the reason a record carries is the first of these, and the
    /// others are carried beside it rather than dropped -- a seam attributed
    /// to a cadence that would have fired on the budget anyway is a seam
    /// whose record answers the wrong question.
    ///
    /// An explicit act outranks every derived one, so the operator comes
    /// first. A phase transition outranks a budget because it changes what
    /// the prompt is FOR; a budget outranks a cadence because it is a limit
    /// and a cadence is a schedule.
    Reason {
        /// The operator declared a boundary. #27's vocabulary named three
        /// triggers and the dogma pins an ask for a fourth
        /// (`AUDIT_Q_HUMAN`); the issue was amended rather than the ask left
        /// unreachable.
        Operator => "operator",
        /// The phase graph ratified a transition.
        Phase => "phase",
        /// The working set reached the declared byte count.
        Budget => "budget",
        /// The declared cadence came round.
        Cadence => "cadence",
    }
}

vocabulary! {
    /// Why a seam rendered without a ratification.
    ///
    /// A seam still fires: the render is the point, and a prompt rebuilt
    /// without an audit is a prompt rebuilt. What does not happen is a fold,
    /// and the reason it did not is typed rather than absent.
    Blocked {
        /// The dogma pins no audit ask for this trigger. Dogma v1 has one for
        /// a phase boundary, one for a scheduled checkpoint and one for an
        /// operator-declared boundary; it has none for a budget threshold,
        /// and inventing the wording would be authoring dogma from a seat
        /// that does not own it.
        NoPinnedAsk => "no_pinned_ask",
        /// The working set is empty, so the audit would be a check of
        /// nothing, and a check of nothing is not a pass.
        NothingToAudit => "nothing_to_audit",
    }
}

/// Which category of working note the audit names.
///
/// One value, because [`crate::object::Entry`] has no slot: the dogma's asks
/// audit `constraints`, `gotchas`, `decisions`, `open_questions` and
/// `next_steps` separately, and the object does not know which an entry is.
/// Auditing everything under one heading is what this module can honestly do
/// today; per-slot asks need the object to carry the slot, which is
/// `diet/object/`'s to add.
pub const AUDIT_CATEGORY: &str = "working notes";

/// The ask a seam puts to the model, and what it is about.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ask {
    /// Why the seam fired.
    pub reason: Reason,
    /// The pinned template the ask was built from.
    pub template: Template,
    /// The ask, filled.
    pub text: String,
    /// The entries handed over, in the order they are numbered in the ask.
    /// A [`Ratifier`]'s answer is per line, so the numbering has to be
    /// somewhere a caller can read rather than re-derive.
    pub items: Vec<EntryId>,
}

/// Something that can answer a seam's ask.
///
/// The trait exists because the answer's GRAMMAR is not this module's: see
/// the note at the top of the file. An implementation parses an answer into
/// patches; this module folds them and records what they moved.
pub trait Ratifier {
    /// The patches `ask`'s answer folds to.
    fn ratify(&mut self, ask: &Ask) -> Vec<Patch>;
}

/// What became of the ratification.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Ratification {
    /// The answer was folded through the reconciler.
    Folded {
        /// How many patches it produced.
        patches: usize,
    },
    /// No ask was put.
    Blocked(Blocked),
}

/// One seam: everything about the moment the prompt was rebuilt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Seam {
    /// Its position in the session, from 1.
    pub index: u32,
    /// The turn it fired after.
    pub at_turn: u32,
    /// Why, in [`Reason`]'s precedence order.
    pub reason: Reason,
    /// Every other trigger that was also true, so a reader can tell a seam
    /// that would have fired anyway from one that would not.
    pub also: Vec<Reason>,
    /// The phase the render was built for.
    pub phase: Option<String>,
    /// The object, dumped before the fold.
    pub before: BTreeMap<EntryId, String>,
    /// The object, dumped after it.
    pub after: BTreeMap<EntryId, String>,
    /// Which entries the fold moved.
    pub moved: BTreeSet<EntryId>,
    /// What the ratification produced.
    pub patches: Vec<Patch>,
    /// What the reconciler did with each.
    pub applied: Vec<Applied>,
    /// Whether there was a ratification at all.
    pub ratified: Ratification,
    /// The prefix the session continues from.
    pub prefix: String,
    /// The working object's version after the fold. #27 asks for a
    /// *versioned* dump either side of a seam; the dumps themselves carry no
    /// header (it would appear in every diff), so the version is recorded
    /// here instead of being unrecoverable.
    pub object_version: u32,
    /// Which frame the prefix was built with. Until the maintainer authors
    /// the frame as dogma, this is [`render::FRAME_VERSION`] and a reader can
    /// tell these renders from renders under the authored one.
    pub frame_version: &'static str,
    /// What the working set measured when the seam fired.
    pub working_set_bytes: u64,
}

impl Seam {
    /// Whether the entries this seam's dumps differ on are exactly the ones
    /// its patches touched.
    ///
    /// The acceptance question for a seam, asked of the seam rather than
    /// reconstructed by a caller: a render that moved an entry no patch names
    /// is a render that edited the object, and the object is not the render's
    /// to edit.
    #[must_use]
    pub fn diff_is_exactly_the_patches(&self) -> bool {
        let touched: BTreeSet<EntryId> = self
            .applied
            .iter()
            .flat_map(Applied::touched)
            .filter(|id| self.before.get(id) != self.after.get(id))
            .collect();
        touched == self.moved
    }
}

/// Why a seam could not be taken.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SeamError {
    /// The reconciler refused the ratification's patches.
    Object(ObjectError),
    /// A pinned ask could not be filled, which is a defect in this module
    /// rather than anything a drive did.
    Fill(FillError),
}

impl fmt::Display for SeamError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Object(why) => write!(f, "the ratification did not apply: {why}"),
            Self::Fill(why) => write!(f, "the seam's ask could not be filled: {why}"),
        }
    }
}

impl Error for SeamError {}

impl From<ObjectError> for SeamError {
    fn from(why: ObjectError) -> Self {
        Self::Object(why)
    }
}

impl From<FillError> for SeamError {
    fn from(why: FillError) -> Self {
        Self::Fill(why)
    }
}

/// The controller.
#[derive(Debug, Clone)]
pub struct Controller<R: Ratifier> {
    policy: Policy,
    ratifier: R,
    phase: Option<String>,
    turn: u32,
    prefix: String,
    seams: Vec<Seam>,
    proposals: Vec<Proposal>,
    /// An operator-declared boundary, waiting for the turn to settle.
    ///
    /// Held rather than acted on for the same reason a ratified transition
    /// is: the turn it was declared in is still running.
    declared: bool,
    /// A transition the graph ratified, waiting for the turn to settle.
    ///
    /// A proposal does not fire a seam the instant it is made: the turn it
    /// was made in is still running, and rebuilding the prompt underneath it
    /// would be the controller acting on the model's judgment at the moment
    /// the model expressed it -- which is the thing the whole design refuses.
    pending: Option<String>,
}

impl<R: Ratifier> Controller<R> {
    /// A controller over `object`, under `policy`.
    ///
    /// The session starts in the graph's first phase, or in no phase where
    /// the graph is empty. The opening prefix is rendered here, so that the
    /// byte-identity claim covers the whole session and not only the part
    /// after the first seam.
    pub fn open(policy: Policy, object: &WorkingObject, ratifier: R) -> Self {
        let phase = policy.phases.first().map(str::to_owned);
        let prefix = render::render(object, phase.as_deref());
        Self {
            policy,
            ratifier,
            phase,
            turn: 0,
            prefix,
            seams: Vec::new(),
            proposals: Vec::new(),
            declared: false,
            pending: None,
        }
    }

    /// The prefix the session is continuing from.
    #[must_use]
    pub fn prefix(&self) -> &str {
        &self.prefix
    }

    /// The phase the session is in.
    #[must_use]
    pub fn phase(&self) -> Option<&str> {
        self.phase.as_deref()
    }

    /// Every seam so far.
    #[must_use]
    pub fn seams(&self) -> &[Seam] {
        &self.seams
    }

    /// The ratifier, so a caller can read what it was asked.
    ///
    /// The asks are the half of a seam that leaves this module, and a test
    /// that could not see them would be checking that the controller talks to
    /// itself.
    #[must_use]
    pub fn ratifier(&self) -> &R {
        &self.ratifier
    }

    /// Every proposal so far, ratified or not.
    #[must_use]
    pub fn proposals(&self) -> &[Proposal] {
        &self.proposals
    }

    /// Begin the next turn.
    pub fn begin_turn(&mut self) -> u32 {
        self.turn += 1;
        self.turn
    }

    /// Declare a boundary. The operator's own act, not the model's.
    ///
    /// No graph rules on it and nothing may refuse it: an operator saying
    /// "we are done with that part" is a fact, and a controller that asked a
    /// phase graph for permission would be treating a person as a proposal.
    /// It fires at the end of the turn it was declared in, like every other
    /// trigger.
    pub fn operator_declares_a_boundary(&mut self) {
        self.declared = true;
    }

    /// Record a phase transition the model proposed, and rule on it.
    ///
    /// The decision is returned AND recorded. A refused proposal fires
    /// nothing and changes nothing; it stays in [`Controller::proposals`],
    /// because the model believing the work had moved on is a fact about the
    /// drive and the one signal that says the graph and the work disagree.
    pub fn propose(&mut self, to: &str) -> Decision {
        let decision = self.policy.phases.decide(self.phase.as_deref(), to);
        if decision == Decision::Ratified {
            self.pending = Some(to.to_owned());
        }
        self.proposals.push(Proposal {
            at_turn: self.turn,
            from: self.phase.clone(),
            to: to.to_owned(),
            decision: decision.clone(),
        });
        decision
    }

    /// Settle the current turn: fire a seam if a trigger says to.
    ///
    /// # Errors
    ///
    /// Returns [`SeamError`] if the reconciler refuses the ratification's
    /// patches, or if a pinned ask could not be filled.
    pub fn settle(&mut self, object: &mut WorkingObject) -> Result<Option<Seam>, SeamError> {
        // One turn, one seam. A second `settle` in the same turn used to fire
        // a second one at the same index -- two full re-prefills for a turn
        // that only ever had one prompt to rebuild.
        if self
            .seams
            .last()
            .is_some_and(|seam| seam.at_turn == self.turn)
        {
            return Ok(None);
        }

        let working_set_bytes = render::working_set_bytes(object);
        let reasons = self.triggers(working_set_bytes);
        let Some(&reason) = reasons.first() else {
            return Ok(None);
        };

        // NOTHING is committed until both fallible steps are through.
        //
        // The phase used to be taken and the pending triggers cleared right
        // here, above the `?`s below -- so a ratifier whose patches the
        // reconciler refused left the controller having advanced its phase,
        // spent the operator's declaration, and recorded no seam. The prefix
        // still rendered the phase the session had left, which is the exact
        // failure the byte-identity design exists to prevent, and the
        // declared boundary never happened at all. The `Ratifier` is the seam
        // to model output, so that is not a rare path.
        let taking = self.pending.clone();
        let phase = taking.clone().or_else(|| self.phase.clone());

        let before = object.dump_lines();
        let (ratified, patches) = self.audit(object, reason)?;
        let applied = object.apply_turn(&patches)?;
        let after = object.dump_lines();
        let moved = changed_between(&before, &after);

        // Past the last `?`. Commit.
        if let Some(to) = taking {
            self.phase = Some(to);
        }
        self.pending = None;
        self.declared = false;
        self.prefix = render::render(object, phase.as_deref());

        let index = u32::try_from(self.seams.len()).unwrap_or(u32::MAX) + 1;
        let seam = Seam {
            index,
            at_turn: self.turn,
            reason,
            also: reasons[1..].to_vec(),
            phase,
            before,
            after,
            moved,
            patches,
            applied,
            ratified,
            prefix: self.prefix.clone(),
            frame_version: render::FRAME_VERSION,
            object_version: object.version(),
            working_set_bytes,
        };
        self.seams.push(seam.clone());
        Ok(Some(seam))
    }

    /// Every trigger that is true right now, in precedence order.
    fn triggers(&self, working_set_bytes: u64) -> Vec<Reason> {
        Reason::ALL
            .iter()
            .copied()
            .filter(|reason| match reason {
                Reason::Operator => self.declared,
                Reason::Phase => self.pending.is_some(),
                Reason::Budget => self
                    .policy
                    .at_working_set_bytes
                    .is_some_and(|at| working_set_bytes >= at),
                // `turn > 0` because turn zero is before the session started,
                // and every number divides zero: without it a controller that
                // settled before its first turn would fire a seam over an
                // empty object.
                Reason::Cadence => self
                    .policy
                    .every_turns
                    .is_some_and(|every| self.turn > 0 && self.turn.is_multiple_of(every)),
            })
            .collect()
    }

    /// Put the audit to the ratifier, or say why it was not put.
    fn audit(
        &mut self,
        object: &WorkingObject,
        reason: Reason,
    ) -> Result<(Ratification, Vec<Patch>), SeamError> {
        let Some(template) = pinned_ask(reason) else {
            return Ok((Ratification::Blocked(Blocked::NoPinnedAsk), Vec::new()));
        };

        let items: Vec<(EntryId, String)> = object
            .live()
            .map(|entry| (entry.id.clone(), entry.content.clone()))
            .collect();
        if items.is_empty() {
            return Ok((Ratification::Blocked(Blocked::NothingToAudit), Vec::new()));
        }

        let numbered = items
            .iter()
            .enumerate()
            .map(|(index, (_, content))| format!("{}. {}", index + 1, render::one_line(content)))
            .collect::<Vec<_>>()
            .join("\n");
        let count = items.len().to_string();
        let text = template.fill(&[
            (Hole::Category, AUDIT_CATEGORY),
            (Hole::LineCount, &count),
            (Hole::Items, &numbered),
        ])?;

        let ask = Ask {
            reason,
            template,
            text,
            items: items.into_iter().map(|(id, _)| id).collect(),
        };
        let patches = self.ratifier.ratify(&ask);
        Ok((
            Ratification::Folded {
                patches: patches.len(),
            },
            patches,
        ))
    }
}

/// The dogma's audit ask for a trigger, where one is pinned.
///
/// A table rather than a guess. The dogma pins an ask for a phase boundary
/// and one for a scheduled checkpoint, and it pins none for a budget
/// threshold: `AUDIT_Q_CADENCE`'s own text says "a cadence fired", so
/// borrowing it for a budget seam would put a sentence in the prompt that is
/// not true. Writing a new one is authoring dogma, which is not this seat's.
#[must_use]
pub fn pinned_ask(reason: Reason) -> Option<Template> {
    match reason {
        Reason::Operator => Some(Template::AuditQHuman),
        Reason::Phase => Some(Template::AuditQ),
        Reason::Cadence => Some(Template::AuditQCadence),
        Reason::Budget => None,
    }
}

