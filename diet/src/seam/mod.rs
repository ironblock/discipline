    fn id(text: &str) -> EntryId {
        EntryId::new(text).expect("a non-blank id")
    }

    fn provenance(turn: u32, index: u32) -> Provenance {
        Provenance {
            turn,
            lane: "ratify".to_owned(),
            fork: None,
            tangent: None,
            index,
        }
    }

    fn add(name: &str, content: &str, turn: u32, index: u32) -> Patch {
        Patch::Add {
            id: id(name),
            content: content.to_owned(),
            provenance: provenance(turn, index),
        }
    }

    /// An object with three live entries, so an audit has something to audit.
    fn three_facts() -> WorkingObject {
        let mut object = WorkingObject::open(regime());
        object
            .apply_turn(&[
                add("e1", "the parser refuses a bare tilde", 1, 0),
                add("e2", "the gate runs on every invocation", 1, 1),
                add("e3", "the register is mined, not authored", 1, 2),
            ])
            .expect("three adds apply");
        object
    }

    fn policy(text: &str) -> Policy {
        Policy::from_regimen(&regimen::parse(text).expect("a regimen")).expect("a policy")
    }

    /// A ratifier that answers from a script and keeps what it was asked.
    #[derive(Debug, Clone, Default)]
    struct Scripted {
        give: Vec<Vec<Patch>>,
        seen: Vec<Ask>,
    }

    impl Scripted {
        fn silent() -> Self {
            Self::default()
        }

        fn answering(give: Vec<Vec<Patch>>) -> Self {
            Self {
                give,
                seen: Vec::new(),
            }
        }
    }

    impl Ratifier for Scripted {
        fn ratify(&mut self, ask: &Ask) -> Vec<Patch> {
            self.seen.push(ask.clone());
            if self.give.is_empty() {
                Vec::new()
            } else {
                self.give.remove(0)
            }
        }
    }

    /// Drive `turns` turns, settling each, and return the prefix after each.
    fn drive(
        controller: &mut Controller<Scripted>,
        object: &mut WorkingObject,
        turns: u32,
    ) -> Vec<String> {
        let mut prefixes = Vec::new();
        for _ in 0..turns {
            controller.begin_turn();
            controller.settle(object).expect("the fold applies");
            prefixes.push(controller.prefix().to_owned());
        }
        prefixes
    }

    // -----------------------------------------------------------------------
    // #27's acceptance rows
