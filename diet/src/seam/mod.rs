    // the policy, read from a regimen
    // -----------------------------------------------------------------------

    #[test]
    fn a_policy_is_read_from_the_regimen_or_refused_with_a_reason() {
        let read = |text: &str| Policy::from_regimen(&regimen::parse(text).expect("a regimen"));

        let full = read(
            "seam_every_turns = 3\n\
             seam_at_working_set_bytes = 4096\n\
             phases = [\"plan\", \"implement\"]\n\
             [phase_transitions]\n\
             plan = [\"implement\"]\n",
        )
        .expect("a policy");
        assert_eq!(full.every_turns, Some(3));
        assert_eq!(full.at_working_set_bytes, Some(4096));
        assert_eq!(
            full.phases.phases(),
            ["plan".to_owned(), "implement".to_owned()]
        );
        assert_eq!(
            full.phases.decide(Some("plan"), "implement"),
            Decision::Ratified
        );

        assert_eq!(
            read("seam_every_turns = 0\n"),
            Err(PolicyError::NotPositive("seam_every_turns")),
            "zero would fire on every turn or on none depending on how it is read; \
             the way to declare no cadence is to leave the key out"
        );
        assert_eq!(
            read("seam_every_turns = \"three\"\n"),
            Err(PolicyError::NotAnInteger("seam_every_turns"))
        );
        assert_eq!(
            read("phases = \"plan\"\n"),
            Err(PolicyError::NotAListOfNames("phases".to_owned()))
        );
        assert_eq!(
            read("phases = [\"plan\", \"plan\"]\n"),
            Err(PolicyError::DuplicatePhase("plan".to_owned())),
            "two phases with one name make an edge's target ambiguous"
        );
        assert_eq!(
            read("phases = [\"plan\"]\n[phase_transitions]\nplan = [\"ship\"]\n"),
            Err(PolicyError::UnknownPhase {
                named: "ship".to_owned(),
                under: "plan".to_owned(),
            }),
            "an edge to a phase that does not exist is a rule nothing can take"
        );
        assert_eq!(
            read("[phase_transitions]\nplan = [\"implement\"]\n"),
            Err(PolicyError::TransitionsWithoutPhases)
        );
    }

