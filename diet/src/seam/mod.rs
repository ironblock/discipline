//! `diet::seam` -- the render-and-ratify controller.
//!
//! Nothing else in this library owns the **render**: the moment the working
//! object is turned into a prompt and the session continues from it. That
//! moment is the architecture's single deliberate prefill event -- everything
//! else exists to make it rare, small and safe -- and it happens here and
//! nowhere else.
//!
//! Two things decide the design.
//!
//! **A seam fires on a deterministic trigger, never on the model's judgment.**
//! A declared cadence, a phase transition the graph ratified, or the working
//! set reaching a declared byte count. Who decides when to compact is the
//! metacognition problem this architecture refuses to hand to the model; the
//! answer is that the work has a shape and the shape decides. The model may
//! *propose* a phase transition, and [`phase::PhaseGraph`] rules on it -- an
//! unratified proposal is recorded and not acted on.
//!
//! **The prefix stays byte-identical between seams.** [`render::render`] is a
//! pure function of the object and the phase, and the controller re-runs it
//! only when a seam fires. That is what makes the claim checkable rather than
//! merely stated.
//!
//! # What is NOT built here, and why
//!
//! The ratification's *answer* is a format, and its grammar is not this
//! seat's to write. The dogma's audit asks want `KEEP` / `UPDATE` / `REMOVE`
//! / `ADD` back, ruling 1 on #25 put that vocabulary in `diet/formats/` as
//! its own verdict enum, and it is not implemented yet. Writing a second
//! parser for it here would be the eleven divergent decline-detectors again.
//!
//! So the controller takes a [`Ratifier`]: it builds the ask, hands over the
//! entries, and folds whatever patches come back. Everything the controller
//! owns -- the triggers, the render, the phase graph, the dumps either side,
//! the fold -- is built and tested. The parse is named as the dependency it
//! is.
//!
//! # What has been seen red
//!
//! **`diet/seam/gate.toml` is the list**, and it is generated by running
//! every entry: each fault is applied to the tree, this lane's tests are run,
//! and `catches` is what actually failed. Twenty-nine of them. The table used
//! to be restated here too, and a table restated in two places is a table
//! that goes stale in one of them.
//!
//! Three are worth naming, because each was a claim the suite could not
//! prove and two of them were found by somebody else looking.
//!
//! **Re-rendering the prefix on every turn changed no test.** Comparing
//! prefixes across turns while the object sits still proves nothing: the
//! render is a pure function, so re-running it on an unchanged object gives
//! the same bytes. The claim is not that the controller renders rarely -- it
//! is that the prefix does not move **while the object does**, and testing it
//! needs a lane writing every turn.
//!
//! **The phase and the pending triggers were committed above the fallible
//! steps.** A ratifier whose patches the reconciler refused left the
//! controller having advanced its phase and spent the operator's declaration
//! with no seam recorded -- rendering a prompt for the phase the session had
//! left. Nothing exercised the error path at all.
//!
//! **The render had no grammar.** Entry content reaches it from model output
//! through the capture lanes, and a note carrying a newline and a tab wrote a
//! whole extra working-set row into the next prefix with an id of the model's
//! choosing. [`render::one_line`] is the fix, and it is the same escaping the
//! audit ask needs so that `{n}` and the number of lines agree.

