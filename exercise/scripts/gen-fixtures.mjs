// Every record `diet check-record` accepts, as a TypeScript module.
//
// For each fixture -- the record corpus's `valid/*.jsonl`, and this package's
// own `fixtures/records/*.jsonl` -- this asks `diet` for its projection and
// writes `src/fixtures/generated/<name>.ts`:
//
//   export const projection = {...} as const satisfies Projection;
//   export const events = [...] as const satisfies readonly Event[];
//   export const lossy = [...] as const;
//
// `events` is `canonical` decoded line by line, and `satisfies readonly
// Event[]` is what checks the hand-written provisional types in
// `src/record/types.ts` against what `diet` actually emits: a field spelled
// differently there fails `pnpm typecheck` on the fixture that carries it.
// The Sequences stories do NOT read `events`; they hand `projection` to the
// app's loader and a test asserts the loader's output equals `events`.
//
// `lossy` names every line that does not survive `JSON.parse` and
// `JSON.stringify` byte for byte -- the record's exact decimals (`0.7000`)
// and any count above 2^53 -- so the loss is a listed fact per fixture and
// never a surprise in a row. It is a byte comparison of two strings, not a
// reading of either.
//
//   node scripts/gen-fixtures.mjs           write the modules
//   node scripts/gen-fixtures.mjs --check   regenerate in memory and diff

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { PACKAGE_ROOT, RECORD_FIXTURES, checkRecord } from './diet.mjs';

const OUT = path.join(PACKAGE_ROOT, 'src', 'fixtures', 'generated');
const HERE = 'scripts/gen-fixtures.mjs';

/** The fixtures, by name, with the path each came from (relative to the repo). */
function fixtures() {
  const found = new Map();
  const dirs = [
    path.join(RECORD_FIXTURES, 'valid'),
    path.join(PACKAGE_ROOT, 'fixtures', 'records'),
  ];
  for (const dir of dirs) {
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).sort()) {
      if (!file.endsWith('.jsonl')) continue;
      const name = file.slice(0, -'.jsonl'.length);
      if (found.has(name)) throw new Error(`two fixtures are named ${name}: ${found.get(name)} and ${path.join(dir, file)}`);
      found.set(name, path.join(dir, file));
    }
  }
  return found;
}

/** `kebab-case` to an identifier, for the registry's keys and imports. */
export function identifier(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[0-9]/, (c) => `_${c}`);
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

function moduleFor(name, file) {
  const { exit, envelope } = checkRecord(file);
  if (exit !== 0 || !envelope.ok) {
    throw new Error(`${path.relative(PACKAGE_ROOT, file)}: diet check-record exited ${exit}: ${envelope.error ?? '(no error)'}`);
  }
  const projection = envelope.value;
  const events = [];
  const lossy = [];
  const lines = projection.canonical.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (line === '') continue;
    const event = JSON.parse(line);
    events.push(event);
    const back = JSON.stringify(event);
    if (back !== line) {
      lossy.push({ line: i + 1, record: event.record, ...(event.id === undefined ? {} : { id: event.id }), canonical: line, decoded: back });
    }
  }
  const relative = path.relative(PACKAGE_ROOT, file).split(path.sep).join('/');
  return [
    `// GENERATED by ${HERE} from ${relative} -- do not edit.`,
    `// The projection is what \`diet check-record\` returned for that file; \`events\``,
    `// is its \`canonical\` decoded line by line, checked against the provisional`,
    `// types at compile time; \`lossy\` lists each line that did not survive the`,
    `// decode byte for byte.`,
    `import type { Event, Projection } from '../../record/types.ts';`,
    ``,
    `export const name = ${literal(name)};`,
    `export const source = ${literal(relative)};`,
    `export const projection = ${literal(projection)} as const satisfies Projection;`,
    `export const events = ${literal(events)} as const satisfies readonly Event[];`,
    `export const lossy = ${literal(lossy)} as const;`,
    ``,
  ].join('\n');
}

function indexFor(names) {
  const lines = [
    `// GENERATED by ${HERE} -- do not edit.`,
    `// Every fixture diet accepts, by name, so a story names a fixture and a`,
    `// typo is a compile error rather than an empty timeline.`,
  ];
  for (const name of names) lines.push(`import * as ${identifier(name)} from './${name}.ts';`);
  lines.push(``, `export const fixtures = {`);
  for (const name of names) lines.push(`  ${literal(name)}: ${identifier(name)},`);
  lines.push(`} as const;`, ``, `export type FixtureName = keyof typeof fixtures;`, ``, `export const fixtureNames = Object.keys(fixtures) as readonly FixtureName[];`, ``);
  return lines.join('\n');
}

const check = process.argv.includes('--check');
const all = fixtures();
const want = new Map();
for (const [name, file] of all) want.set(`${name}.ts`, moduleFor(name, file));
want.set('index.ts', indexFor([...all.keys()]));

if (check) {
  const failures = [];
  const have = existsSync(OUT) ? new Set(readdirSync(OUT)) : new Set();
  for (const [file, text] of want) {
    const at = path.join(OUT, file);
    if (!existsSync(at)) failures.push(`${file}: missing; run \`pnpm gen\``);
    else if (readFileSync(at, 'utf8') !== text) failures.push(`${file}: differs from what diet emits now; run \`pnpm gen\``);
    have.delete(file);
  }
  for (const stale of have) failures.push(`${stale}: no fixture produces it any more; run \`pnpm gen\``);
  if (failures.length > 0) {
    console.error(failures.join('\n'));
    process.exit(1);
  }
  console.log(`gen-fixtures: ${all.size} generated module(s) match diet's output`);
} else {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  for (const [file, text] of want) writeFileSync(path.join(OUT, file), text);
  console.log(`gen-fixtures: wrote ${all.size} module(s) to ${path.relative(PACKAGE_ROOT, OUT)}`);
}
